export function ending(win, notesFound, solo) {
  const total = NOTES.length;
  if (!win) return {
    title: solo ? 'Ты остался внизу' : 'Никто не поднялся',
    text: 'Шахту «Глубокая» закрыли весной 1988 года. Ствол залили бетоном. Тела горноспасателей, как и смену Ковалёва, так и не нашли.'
  };
  if (notesFound >= total) return {
    title: solo ? 'Ты поднялся' : 'Вы поднялись',
    text: 'Клеть шла наверх медленно, скрипя на каждом метре. Вы стояли спиной к решётке и смотрели на свет над головой. Никто не обернулся. Никто не заметил, что клеть стала тяжелее. Шахту закрыли весной. В деревне наверху с тех пор не гасят свет по ночам.'
  };
  return {
    title: solo ? 'Ты поднялся' : 'Вы поднялись',
    text: `Клеть пошла вверх. Внизу, в луче фонаря, в последний раз мелькнула мешковина — она стояла у решётки и смотрела вслед. Вы так и не узнали, что случилось со сменой Ковалёва. Записок найдено: ${notesFound} из ${total}.`
  };
}
