export function finalEnding(win, notesFound, solo, chapterIdx) {
  const last = chapterIdx === CHAPTERS.length - 1;
  if (!win) return {
    title: solo ? 'Ты остался внизу' : 'Никто не поднялся',
    text: last
      ? 'Ворот остановился на середине. Бадья повисла в темноте ствола, слегка покачиваясь. Снизу на неё смотрели. Долго.'
      : 'Шахту «Глубокая» закрыли весной 1988 года. Ствол залили бетоном. Горноспасателей, как и смену Ковалёва, так и не нашли.'
  };
  if (!last) return { title: 'Глава пройдена', text: CHAPTERS[chapterIdx].outro };
  if (notesFound >= TOTAL_NOTES) return {
    title: 'Свет',
    text: 'Бадья вышла на поверхность в сером рассвете. Вы подожгли шнур, как велел Ковалёв, и отбежали. Земля под ногами вздохнула и просела. Шахту «Глубокая» больше никто не откроет. Иногда по ночам из-под бетона слышно, как кто-то тихо зовёт по имени. Но свет в деревне больше не гаснет, и она спит.'
  };
  return {
    title: 'Рассвет',
    text: `Бадья вышла на поверхность в сером рассвете. Вы выбрались, щурясь от света, и не сразу заметили, что ворот продолжает крутиться сам. Снизу поднималось что-то ещё. Вы нашли ${notesFound} записок из ${TOTAL_NOTES} — и так и не узнали, что Ковалёв просил подорвать ствол.`
  };
}
